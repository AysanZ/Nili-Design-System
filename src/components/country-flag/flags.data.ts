/**
 * The flag *catalogue* — codes and English names only.
 *
 * The artwork itself is not here. 444 flags inlined as strings is ~320 KB of
 * JavaScript that every consumer parses on load whether or not they render a
 * flag, so the SVGs are served as static files from `public/flags/<code>.svg`
 * and this file just says which ones exist. That keeps the JS payload at a few
 * kilobytes, lets the browser cache each flag independently, and means a
 * country picker's flags stream in as rows scroll instead of blocking the
 * bundle.
 *
 * The trade: a flag is an `<img>`, so it cannot inherit `currentColor` or a
 * CSS filter from its parent. Flags are full-colour artwork with fixed
 * national colours, so there is nothing to inherit — this costs nothing here,
 * but it is why the icon set went the other way.
 *
 * Artwork: HatScripts/circle-flags (MIT) — see `public/flags/LICENSE.md`.
 *
 * GENERATED FILE. Regenerate with `node scripts/build-flags.mjs`.
 */

